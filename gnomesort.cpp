#include "gnomesort.h"

#include <utility> // std::swap

std::vector<int> gnomeSort(std::vector<int> input)
{
    // Гномья сортировка:
    // Идея: идём по массиву вперёд, пока порядок не нарушен.
    // Если нарушен (a[i] < a[i-1]) — меняем элементы местами и шагаем назад.
    // Так элементы постепенно "проталкиваются" на своё место, как гном в классическом объяснении.

    if (input.size() < 2) {
        return input; // Если элементов 0 или 1 — массив уже отсортирован
    }

    std::size_t i = 1; // Индекс текущего элемента
    while (i < input.size()) {
        if (i == 0 || input[i - 1] <= input[i]) {
            ++i; // Порядок верный — идём дальше
        } else {
            std::swap(input[i - 1], input[i]); // Меняем местами "неправильную" пару
            --i;                                // Делаем шаг назад и продолжаем проверку
        }
    }

    return input; // Возвращаем отсортированную копию
}
